      text += `输入回退: ${satelliteParams.BOi} dB | 输出回退: ${satelliteParams.BOo} dB\n`;
      text += `卫星EIRP: ${results.EIRPsResult} dBW | 卫星SFD: ${results.SFDsResult} dBW/m²\n`;
      text += `卫星PSD: ${results.satellitePSDResult} dBW/Hz | 地面PFD: ${results.satellitePFD} dBW/m²\n\n`;
      text += `【Ⅲ. 链路质量】\n`;
      text += `综合C/N: ${results.carrierTotalCN}dB | 门限C/N: ${results.thresholdCN}dB | 余量: ${results.linkmargin}dB\n`;
      text += `Es/N₀: ${results.esnoResult}dB | 可用度: ${results.systemAvailabilityResult}% | BER: ${results.berResult}\n\n`;
