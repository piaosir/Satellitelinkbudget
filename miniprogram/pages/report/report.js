      text += `Total C/N: ${results.carrierTotalCN}dB | Threshold C/N: ${results.thresholdCN}dB | Margin: ${results.linkmargin}dB\n`;
      text += `Es/N₀: ${results.esnoResult}dB | Availability: ${results.systemAvailabilityResult}% | BER: ${results.berResult}\n\n`;
      text += `【Ⅳ. UPLINK】${linkParams.earthStationLocation}\n`;
      text += `Antenna: ${results.earthAntennaDiameterResult}m / ${results.txAntennaGainResult}dB | Power: ${results.selectedPowerWResult}W (${results.selectedPowerResult}dBW)\n`;
