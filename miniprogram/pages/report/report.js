      text += `FSL: ${results.uplinkFSLResult}dB | Rain: ${results.uplinkRainAttenuation}dB | Uplink C/N: ${results.uplinkCN}dB\n\n`;
      text += `【Ⅴ. DOWNLINK】${linkParams.rxEarthStationLocation}\n`;
      text += `Antenna: ${results.rxAntennaDiameterResult}m / ${results.rxAntennaGainResult}dB | G/T: ${results.gOverTeResult} dB/K\n`;
      text += `EIRP Output: ${results.RXeirpPerCarrierResult} dBW | Elevation: ${results.rxElevationResult}° | Polar: ${results.downlinkPolarizationResult}\n`;
      text += `FSL: ${results.downlinkFSLResult}dB | Rain: ${results.downlinkRainAttenuationResult}dB | Downlink C/N: ${results.downlinkCN}dB\n\n`;
      text += `【Ⅵ. RESOURCE USAGE】\n`;
      text += `Bandwidth: ${results.bandwidthUsageRatio}% | Power: ${results.powerUsageRatio}%\n`;
      text += `Recommended Power: ${results.paRecommendation}W (${results.paRecommendationdBResult}dBW)\n`;
      text += `━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n`;
