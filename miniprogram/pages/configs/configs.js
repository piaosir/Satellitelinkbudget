  // 扫描二维码导入
  scanQRCode() {
    wx.scanCode({
      onlyFromCamera: false,
      success: async (res) => {
        console.log('扫码结果:', res);
        console.log('扫码类型:', res.scanType);
        console.log('扫码结果值:', res.result);
        console.log('扫码路径:', res.path);
        
        // 小程序码在小程序内扫描时，result 为空，需要从 path 中提取
        if (res.scanType === 'WX_CODE') {
          // 小程序码：尝试从 path 中提取 scene 参数
          if (res.path) {
            const sceneMatch = res.path.match(/scene=([^&]+)/);
            if (sceneMatch) {
              const code = decodeURIComponent(sceneMatch[1]);
              console.log('从 path 提取的 scene:', code);
              
              if (code.startsWith('B')) {
                await this.importFromBatchCode(code);
                return;
              } else {
                await this.importFromShareCode(code);
                return;
              }
            }
          }
          
          // 如果无法从 path 提取，提示用户使用微信扫一扫
          wx.showModal({
            title: '提示',
            content: '请使用微信"扫一扫"功能扫描此小程序码，或直接输入分享码导入',
            confirmText: '输入分享码',
            cancelText: '取消',
            success: (modalRes) => {
              if (modalRes.confirm) {
                this.inputShareCode();
              }
            }
          });
          return;
        }
        
        // 普通二维码
        if (res.result) {
          let code = res.result;
          
          // 如果是完整URL，提取分享码
          if (code.includes('shareCode=')) {
            const match = code.match(/shareCode=([^&]+)/);
            if (match) {
              code = match[1];
            }
          }
          
          // 判断是批次码还是单个分享码
          if (code.startsWith('B')) {
            await this.importFromBatchCode(code);
          } else {
            await this.importFromShareCode(code);
          }
        } else {
          wx.showToast({
            title: '无法识别二维码',
            icon: 'none'
          });
        }
      },
      fail: (error) => {
        console.error('扫码失败:', error);
        wx.showToast({
          title: '扫码失败',
          icon: 'none'
        });
      }
    });
  },

