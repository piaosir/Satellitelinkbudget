  // 执行保存操作（优先云端，失败则本地）
  async doSaveConfig(configName) {
    wx.showLoading({
      title: '保存中...',
      mask: true
    });
    
    try {
      // 尝试调用云函数保存配置
      const res = await wx.cloud.callFunction({
        name: 'configManager',
        data: {
          action: 'save',
          data: {
            configName: configName,
            satelliteParams: app.globalData.satelliteParams,
            linkParams: app.globalData.linkParams,
            calculationResults: app.globalData.calculationResults || {},
            noiseRatioMode: app.globalData.noiseRatioMode || 'ebno',
            markedParams: app.globalData.markedParams || [],
            highlightedRows: app.globalData.highlightedRows || []
          }
        }
      });
      
      console.log('保存结果:', res);
      
      if (res.result && res.result.success) {
        // 云端保存成功，不需要本地保存
        wx.showToast({
          title: '已保存到云端',
          icon: 'success'
        });
        
        // 刷新列表
        setTimeout(() => {
          this.loadConfigs();
        }, 1000);
      } else {
        throw new Error(res.result?.error || '保存失败');
      }
    } catch (error) {
      console.error('保存到云端失败:', error);
      
      // 云端保存失败时，保存到本地
      this.saveToLocal(configName);
      
      // 检查是否是云函数未部署的错误
      const errorMsg = error.message || '';
      const isCloudFunctionMissing = errorMsg.includes('-501000') || 
                                      errorMsg.includes('FUNCTION_NOT_FOUND') ||
                                      errorMsg.includes('FunctionName');
      
      if (isCloudFunctionMissing) {
        wx.showModal({
          title: '提示',
          content: '云函数尚未部署，配置已保存到本地。\n\n请在微信开发者工具中右键点击 cloudfunctions/configManager 文件夹，选择"上传并部署：云端安装依赖"',
          showCancel: false,
          confirmText: '知道了'
        });
      } else {
        wx.showToast({
          title: '已保存到本地',
          icon: 'success'
        });
      }
      
      // 刷新列表显示本地配置
      setTimeout(() => {
        this.loadConfigs();
      }, 1000);
    } finally {
      wx.hideLoading();
    }
  },

