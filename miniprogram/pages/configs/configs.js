  // 获取配置数据（从本地或云端）
  async getConfigsData(configIds) {
    const configsData = [];
    
    for (const configId of configIds) {
      const config = this.data.configs.find(c => c._id === configId);
      if (!config) continue;
      
      if (config.isLocal) {
        // 本地配置，直接从storage获取完整数据
        const localConfigs = wx.getStorageSync('savedConfigs') || [];
        const fullConfig = localConfigs.find(c => c._id === configId);
        if (fullConfig) {
          configsData.push(fullConfig);
        }
      } else {
        // 云端配置，调用云函数获取
        try {
          const res = await wx.cloud.callFunction({
            name: 'configManager',
            data: {
              action: 'load',
              data: { configId }
            }
          });
          if (res.result && res.result.success && res.result.config) {
            configsData.push(res.result.config);
          }
        } catch (error) {
          console.error('获取云端配置失败:', configId, error);
        }
      }
    }
    
    return configsData;
  },

